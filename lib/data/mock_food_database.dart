  static List<FoodItem> _builtIn(List<FoodItem> foods) => [
    for (final f in foods) f.copyWith(nutritionSource: NutritionSource.builtIn),
  ];

  /// Retrieve all built-in food items
  static List<FoodItem> getAllFoods() => List.unmodifiable(defaultFoods);

  /// Get foods matching a specific category
  static List<FoodItem> getFoodsByCategory(String category) {
    final cat = category.toLowerCase().trim();
    if (cat == 'all' || cat.isEmpty) return getAllFoods();

    if (cat == 'carbohydrates' || cat == 'carbs') {
      return defaultFoods
          .where(
            (f) =>
                f.category.toLowerCase() == 'grains' ||
                f.category.toLowerCase() == 'indian' ||
                f.carbohydrates > 15,
          )
          .toList();
    }
    if (cat == 'fats' || cat == 'fat') {
      return defaultFoods
          .where(
            (f) =>
                f.fats > 8 ||
                f.category.toLowerCase() == 'snacks' ||
                f.category.toLowerCase() == 'packaged',
          )
          .toList();
    }
    return defaultFoods.where((f) => f.category.toLowerCase() == cat).toList();
  }

  /// Retrieve a specific food item by its unique ID
  static FoodItem? getFoodById(String id) {
    try {
      return defaultFoods.firstWhere((f) => f.id == id);
    } catch (_) {
      return null;
    }
  }

  /// Search foods by query string across name, brand, category, altNames, and description
  static List<FoodItem> searchFoods(String query) {
    if (query.trim().isEmpty) return getAllFoods();
    final q = query.toLowerCase().trim();
    return defaultFoods.where((f) {
      final nameMatch = f.name.toLowerCase().contains(q);
      final brandMatch = f.brand?.toLowerCase().contains(q) ?? false;
      final catMatch = f.category.toLowerCase().contains(q);
      final altMatch = f.altNames.any((alt) => alt.toLowerCase().contains(q));
      final descMatch = f.description.toLowerCase().contains(q);
      return nameMatch || brandMatch || catMatch || altMatch || descMatch;
    }).toList();
  }
